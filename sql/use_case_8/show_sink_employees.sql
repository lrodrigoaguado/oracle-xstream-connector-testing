-- Use Case 8 (runs against SINKPDB): pretty-print the replicated EMPLOYEES table.
SET LINESIZE 200 PAGESIZE 50 TRIMSPOOL ON TAB OFF FEEDBACK ON
COLUMN "EMPLOYEE_ID"     FORMAT 999     HEADING "ID"
COLUMN "FIRST_NAME"      FORMAT A10     HEADING "FIRST"
COLUMN "LAST_NAME"       FORMAT A10     HEADING "LAST"
COLUMN "EMAIL"           FORMAT A26
COLUMN "SALARY"          FORMAT 999,999
COLUMN "DEPARTMENT"      FORMAT A20
COLUMN "SOURCETIMESTAMP" FORMAT A19     HEADING "SOURCE TS"
COLUMN "SINKTIMESTAMP"   FORMAT A19     HEADING "SINK TS"
SELECT "EMPLOYEE_ID", "FIRST_NAME", "LAST_NAME", "EMAIL", "SALARY", "DEPARTMENT",
       TO_CHAR("SOURCETIMESTAMP",'YYYY-MM-DD HH24:MI:SS') AS "SOURCETIMESTAMP",
       TO_CHAR("SINKTIMESTAMP",'YYYY-MM-DD HH24:MI:SS')   AS "SINKTIMESTAMP"
FROM "EMPLOYEES" ORDER BY "EMPLOYEE_ID";
